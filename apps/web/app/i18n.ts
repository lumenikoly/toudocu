export type MessageKey = keyof (typeof catalogs)['en'];

export function translator(locale: Locale) {
  return {
    sectionTitle: (value: string): string => {
      const labels: Record<string, [string, string]> = {
        architecture: ['Architecture', 'Архитектура'],
        modules: ['Modules', 'Модули'],
        'use-cases': ['Use cases', 'Сценарии'],
        flows: ['Processes', 'Процессы'],
        screens: ['Screens', 'Экраны'],
        decisions: ['Decisions', 'Решения'],
        contracts: ['Contracts', 'Контракты'],
        quality: ['Quality standards', 'Стандарты качества'],
        runbooks: ['Runbooks', 'Инструкции'],
        reference: ['Reference', 'Справочник'],
        guides: ['Guides', 'Руководства'],
        work: ['Tasks', 'Задачи'],
        drafts: ['Drafts', 'Черновики'],
      };
      return labels[value]?.[locale === 'ru' ? 1 : 0] ?? value;
    },
    text: (key: MessageKey): string => catalogs[locale][key],
    format: (key: MessageKey, values: Record<string, string | number>): string =>
      Object.entries(values).reduce<string>(
        (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
        String(catalogs[locale][key]),
      ),
    status: (value: string): string => statusLabels[locale][value] ?? value,
    changeStatus: (value: string): string => {
      const labels: Record<string, [string, string]> = {
        added: ['Added', 'Добавлен'],
        modified: ['Modified', 'Изменён'],
        deleted: ['Deleted', 'Удалён'],
        renamed: ['Renamed', 'Переименован'],
        copied: ['Copied', 'Скопирован'],
        untracked: ['Untracked', 'Не отслеживается'],
        'type-changed': ['Type changed', 'Изменён тип'],
        linked: ['Linked', 'Связан'],
      };
      return labels[value]?.[locale === 'ru' ? 1 : 0] ?? value;
    },
    documentType: (value: string): string => {
      const labels: Record<string, [string, string]> = {
        overview: ['Overview', 'Обзор'],
        architecture: ['Architecture', 'Архитектура'],
        module: ['Module', 'Модуль'],
        'use-case': ['Use case', 'Сценарий'],
        flow: ['Process', 'Процесс'],
        screen: ['Screen', 'Экран'],
        decision: ['Decision', 'Решение'],
        contract: ['Contract', 'Контракт'],
        standard: ['Standard', 'Стандарт'],
        runbook: ['Runbook', 'Инструкция'],
        reference: ['Reference', 'Справочник'],
        guide: ['Guide', 'Руководство'],
        task: ['Task', 'Задача'],
        bug: ['Bug', 'Ошибка'],
        work: ['Work item', 'Рабочая задача'],
        draft: ['Draft', 'Черновик'],
        document: ['Document', 'Документ'],
      };
      return labels[value]?.[locale === 'ru' ? 1 : 0] ?? value.replaceAll('-', ' ');
    },
  };
}
